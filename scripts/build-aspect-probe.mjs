#!/usr/bin/env node
/**
 * Build the aspect-ratio probe: a test card, and a snippet that fills three
 * differently-shaped rectangles with it.
 *
 * This is probe question 8, and it is the one question no API can answer.
 * `ShapeFill.setImage` reports nothing about what it did with the image, so the
 * only instrument is a person looking at a slide — which is why this produces a
 * PICTURE rather than an answer sheet.
 *
 * The card is square and carries a circle, a grid of squares, 45-degree
 * diagonals and a label in each corner. Those four make the three possible
 * outcomes tell each other apart at a glance, which a photograph of an
 * arbitrary image would not:
 *
 *   stretched     the circle is an ellipse, and all four corner labels survive
 *   cropped       the circle stays round and some corner labels are gone
 *   letterboxed   the circle stays round, every corner survives, bars appear
 *
 * Rendered through the same Chromium `pane-shots.mjs` uses rather than checked
 * in as bytes, so the card and the reason it looks like that live together.
 *
 *   node scripts/build-aspect-probe.mjs
 */
import { writeFileSync } from "node:fs";
import { chromium } from "playwright";
import { isMain } from "./is-main.mjs";

const SIZE = 420;

/** The card, as an SVG document. Square on purpose — see the header. */
export function cardSvg(size = SIZE) {
  const s = size;
  const m = s / 2;
  const grid = [];
  for (let i = 1; i < 10; i++) {
    const at = ((s / 10) * i).toFixed(1);
    grid.push(`M${at} 0V${s}`, `M0 ${at}H${s}`);
  }
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 ${s} ${s}">` +
    `<rect width="${s}" height="${s}" fill="#ffffff"/>` +
    `<g stroke="#cbd5e0" stroke-width="1.5"><path d="${grid.join("")}"/></g>` +
    `<path d="M0 0L${s} ${s}M${s} 0L0 ${s}" stroke="#ed8936" stroke-width="2" opacity="0.7"/>` +
    `<circle cx="${m}" cy="${m}" r="${m * 0.9}" fill="none" stroke="#2b6cb0" stroke-width="7"/>` +
    `<circle cx="${m}" cy="${m}" r="${m * 0.5}" fill="none" stroke="#2b6cb0" stroke-width="4"/>` +
    `<rect x="${m * 0.37}" y="${m * 0.37}" width="${s - m * 0.74}" height="${s - m * 0.74}" fill="none" stroke="#00254c" stroke-width="3"/>` +
    `<g font-family="Segoe UI, Arial, sans-serif" font-size="24" font-weight="700" fill="#00254c">` +
    `<text x="12" y="32">TL</text><text x="${s - 12}" y="32" text-anchor="end">TR</text>` +
    `<text x="12" y="${s - 12}">BL</text><text x="${s - 12}" y="${s - 12}" text-anchor="end">BR</text></g>` +
    `<g font-family="Segoe UI, Arial, sans-serif" text-anchor="middle" fill="#00254c">` +
    `<text x="${m}" y="${m - 10}" font-size="45" font-weight="700">1:1</text>` +
    `<text x="${m}" y="${m + 22}" font-size="18">square source</text>` +
    `<text x="${m}" y="${m + 52}" font-size="15" fill="#5b6672">circle round = aspect kept</text></g>` +
    `</svg>`
  );
}

/**
 * The three shapes, and why these three.
 *
 * One square, one wide, one tall, all filled from the SAME square card. A
 * single shape cannot answer: a circle in a square box looks correct whatever
 * the host does with it. The two off-square boxes are the measurement, and
 * having both says which AXIS was stretched rather than only that something
 * was.
 */
export const BOXES = [
  { label: "1:1 square", left: 40, top: 130, width: 240, height: 240 },
  { label: "2:1 wide", left: 310, top: 130, width: 400, height: 200 },
  { label: "1:2 tall", left: 745, top: 130, width: 140, height: 280 },
];

export function snippetFor(cardBase64, boxes = BOXES) {
  return `/*
 * SSF Merge — aspect-ratio probe (question 8)
 *
 * Paste this whole file into a blank Script Lab snippet in PowerPoint and press
 * Run. It draws THREE rectangles on the LAST slide of the deck and fills each
 * with the same SQUARE test card, through the call image fields would use:
 * \`ShapeFill.setImage\` (PowerPointApi 1.10).
 *
 * Then LOOK AT THE SLIDE and send a screenshot. Nothing is printed, because
 * nothing can be: no API reports what the host did with the image, which is
 * why this question outlived the other seven.
 *
 *   the circle is an ELLIPSE in the wide and tall boxes  -> the host STRETCHES,
 *                                                           and the engine has
 *                                                           to letterbox before
 *                                                           sending
 *   the circle stays ROUND and corner labels are missing -> the host CROPS
 *   the circle stays ROUND and every corner survives     -> the host letterboxes
 *
 * It adds no slides and deletes nothing. The three shapes are ordinary shapes
 * on your last slide: select them and press Delete when you are done.
 *
 * Generated by scripts/build-aspect-probe.mjs — do not edit here.
 */

const CARD = "${cardBase64}";

const BOXES = ${JSON.stringify(boxes, null, 2)};

async function run() {
  await PowerPoint.run(async (context) => {
    // The LAST slide, by position. A slide this run has just added does not
    // round-trip through getItem(id) on the web, so nothing is added at all.
    const slides = context.presentation.slides;
    slides.load("items/id");
    await context.sync();
    const slide = slides.items[slides.items.length - 1];
    if (!slide) throw new Error("this deck has no slides to draw on");

    for (const box of BOXES) {
      const shape = slide.shapes.addGeometricShape("Rectangle", {
        left: box.left,
        top: box.top,
        width: box.width,
        height: box.height,
      });
      // The call an image field would make. Queued in the SAME batch that
      // created the shape: a shape proxy does not survive a context.sync() on
      // this host, and touching it again answers InvalidParam.
      shape.fill.setImage(CARD);
    }
    await context.sync();
  });

  console.log("Three shapes are on the LAST slide: square, then wide, then tall.");
  console.log("Look at the blue circle in each one, then send a screenshot.");
  console.log("Round in all three = the host preserves aspect ratio.");
}

$("#run").click(() => tryCatch(run));

async function tryCatch(callback) {
  try {
    await callback();
  } catch (error) {
    console.error(error);
  }
}
`;
}

export async function main() {
  const browser = await chromium.launch({
    executablePath: process.env.CHROMIUM ?? "/opt/pw-browsers/chromium-1194/chrome-linux/chrome",
  });
  const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE }, deviceScaleFactor: 1 });
  await page.setContent(`<!doctype html><meta charset="utf-8"><style>html,body{margin:0}</style>${cardSvg()}`);
  const png = await page.screenshot({ type: "png" });
  await browser.close();

  writeFileSync("probe/aspect-card.png", png);
  const snippet = snippetFor(png.toString("base64"));
  writeFileSync("probe/aspect-probe.ts", snippet);
  console.log(`probe/aspect-card.png (${png.length} bytes) and probe/aspect-probe.ts (${snippet.length} bytes)`);
}

if (isMain(import.meta.url)) await main();
